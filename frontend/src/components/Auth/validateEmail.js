// ------ Функция проверки электронной почты ------ //
export function validateEmail(value) {

    // ------ Удаляем пробелы по краям ------ //
    const email = value.trim()

    // ------ Пустое поле не показывает ошибку во время ввода ------ //
    if (email.length === 0) {
        return ''
    }

    // ------ Проверяем наличие пробелов внутри почты ------ //
    if (email.includes(' ')) {
        return 'Почта не должна содержать пробелы'
    }

    // ------ Ограничиваем общую длину почты ------ //
    if (email.length > 254) {
        return 'Почта слишком длинная'
    }

    // ------ Проверяем базовый формат электронной почты ------ //
    const emailPattern = /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/

    if (!emailPattern.test(email)) {
        return 'Введите почту в формате name@mail.ru'
    }

    // ------ Получаем домен электронной почты ------ //
    const emailDomain = email
        .split('@')[1]
        .toLowerCase()

    // ------ Запрещаем почтовые адреса Gmail ------ //
    if (
        emailDomain === 'gmail.com'
    ) {
        return 'Регистрация с почтой Gmail недоступна'
    }

    // ------ Ошибок нет ------ //
    return ''
}